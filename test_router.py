from core.model_router import ModelRouter


def main():

    print("=" * 60)
    print("ProgramMind ModelRouter 测试")
    print("=" * 60)

    # --------------------------------------------------------
    # 创建路由器
    # --------------------------------------------------------

    router = ModelRouter()

    # --------------------------------------------------------
    # 测试任务
    # --------------------------------------------------------

    test_tasks = [
        "教学",
        "答疑",
        "知识库",
        "RAG",
        "学习规划",
        "备课",
        "代码",
        "算法",
        "论文",
        "科研",
    ]

    # --------------------------------------------------------
    # 开始测试
    # --------------------------------------------------------

    for task in test_tasks:

        model = router.route(
            task
        )

        print()
        print(
            f"测试：{task}"
        )

        print(
            f"选择模型：{model}"
        )

    # --------------------------------------------------------
    # 测试结束
    # --------------------------------------------------------

    print()
    print("=" * 60)
    print("Router 测试结束")
    print("=" * 60)


if __name__ == "__main__":

    main()